export const LANGUAGES = ['en', 'ur'];

/** Looks a dotted key up in the dictionary and fills in {placeholders}. */
export function translate(language, key, vars = {}) {
  const lang = LANGUAGES.includes(language) ? language : 'en';
  const read = (dictionary) => key.split('.').reduce((value, part) => (value == null ? value : value[part]), dictionary);
  let value = read(dictionaries[lang]);
  if (value === undefined) value = read(dictionaries.en);
  if (value === undefined) return key;
  if (typeof value !== 'string') return String(value);
  return value.replace(/\{(\w+)\}/g, (_, name) => (vars[name] === undefined ? `{${name}}` : String(vars[name])));
}

/** Brand name in the requested language, falling back to the English name. */
export function brandLabel(language, brand) {
  const table = dictionaries[language]?.brands || dictionaries.en.brands;
  return table[brand] || brand;
}

/** Turns 2550000 into "PKR 25.5 Lac" / "25.5 لاکھ روپے" style short labels. */
export function shortPrice(value, language = 'en') {
  const amount = Number(value) || 0;
  const crore = amount / 10_000_000;
  const lac = amount / 100_000;
  const thousands = amount / 1_000;
  if (language === 'ur') {
    if (crore >= 1) return `${trim(crore)} کروڑ`;
    if (lac >= 1) return `${trim(lac)} لاکھ`;
    return `${Math.round(thousands)} ہزار`;
  }
  if (crore >= 1) return `${trim(crore)} crore`;
  if (lac >= 1) return `${trim(lac)} lac`;
  return `${Math.round(thousands)}k`;
}

function trim(number) {
  return Number(number.toFixed(number >= 100 ? 0 : number >= 10 ? 1 : 1)).toString();
}
